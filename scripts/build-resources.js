// Scans the NFS_Resources folder tree and emits resources-data.js, which the
// in-app submenu (resources.html) reads at load time. Re-run this whenever the
// .url shortcuts or PDFs under NFS_Resources change:
//
//     npm run build:resources
//
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const NFS = path.join(ROOT, 'NFS_Resources');
const SECTORS_DIR = path.join(NFS, 'Explore Sectors on NFS');

// Pull the URL= line out of a Windows .url InternetShortcut file.
function readUrl(file) {
  const txt = fs.readFileSync(file, 'utf8');
  const m = txt.match(/^URL=(.*)$/m);
  return m ? m[1].trim() : null;
}

function titleFromUrlFile(name) {
  return name.replace(/\.url$/i, '').replace(/\s+on NFS$/i, '').trim();
}

// app-root-relative, forward-slashed path (safe to pass over IPC)
function relPath(abs) {
  return path.relative(ROOT, abs).split(path.sep).join('/');
}

const data = { links: [], sectors: [] };

// Top-level .url shortcuts (Data Visualisation, Best Practices, KPIs, ...)
for (const entry of fs.readdirSync(NFS, { withFileTypes: true })) {
  if (entry.isFile() && entry.name.toLowerCase().endsWith('.url')) {
    const url = readUrl(path.join(NFS, entry.name));
    if (url) data.links.push({ title: titleFromUrlFile(entry.name), url });
  }
}
data.links.sort((a, b) => a.title.localeCompare(b.title));

// Per-sector folders: each has one .url (the sector's NFS page) + PDFs.
if (fs.existsSync(SECTORS_DIR)) {
  for (const sec of fs.readdirSync(SECTORS_DIR, { withFileTypes: true })) {
    if (!sec.isDirectory()) continue;
    const secPath = path.join(SECTORS_DIR, sec.name);
    const sector = { name: sec.name, url: null, docs: [] };
    for (const f of fs.readdirSync(secPath, { withFileTypes: true })) {
      if (!f.isFile()) continue;
      const lower = f.name.toLowerCase();
      if (lower.endsWith('.url')) {
        sector.url = readUrl(path.join(secPath, f.name));
      } else if (lower.endsWith('.pdf')) {
        sector.docs.push({
          title: f.name.replace(/\.pdf$/i, ''),
          rel: relPath(path.join(secPath, f.name)),
        });
      }
    }
    sector.docs.sort((a, b) => a.title.localeCompare(b.title));
    data.sectors.push(sector);
  }
}
data.sectors.sort((a, b) => a.name.localeCompare(b.name));

const out = '// AUTO-GENERATED by scripts/build-resources.js — do not edit by hand.\n' +
  'window.RESOURCES = ' + JSON.stringify(data, null, 2) + ';\n';
fs.writeFileSync(path.join(ROOT, 'resources-data.js'), out, 'utf8');

const pdfCount = data.sectors.reduce((n, s) => n + s.docs.length, 0);
console.log(
  `Wrote resources-data.js: ${data.links.length} links, ` +
  `${data.sectors.length} sectors, ${pdfCount} PDFs.`
);
