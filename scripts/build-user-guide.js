// Scans assets/English Version and assets/Hindi Version for videos and emits
// user-guide-data.js, consumed by user-guide.html at runtime. Re-run this
// whenever videos are added/removed:
//
//     npm run build:resources
//
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const ASSETS = path.join(ROOT, "assets");
const VIDEO_EXT = /\.(mp4|webm|mov|m4v|mkv)$/i;

// App-root-relative, forward-slashed path — safe to pass over IPC to main's
// open-doc handler, which resolves it against APP_ROOT.
function relPath(abs) {
  return path.relative(ROOT, abs).split(path.sep).join("/");
}

function listVideos(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((f) => f.isFile() && VIDEO_EXT.test(f.name))
    .map((f) => ({
      title: f.name.replace(VIDEO_EXT, "").trim(),
      rel: relPath(path.join(dir, f.name)),
    }))
    .sort((a, b) => a.title.localeCompare(b.title, undefined, { numeric: true }));
}

const data = {
  // The training guide is a single PDF — already shipped at assets/user-guide.pdf.
  trainingGuide: {
    title: "Training Guide",
    rel: "assets/user-guide.pdf",
  },
  sop:{
    title: "SOP",
    rel: "assets/Final SOP_NITI TARA Execution.pdf",
  },
  // Self-learning videos, by language.
  videos: {
    english: listVideos(path.join(ASSETS, "English Version")),
    hindi: listVideos(path.join(ASSETS, "Hindi Version")),
  },
};

const out =
  "// AUTO-GENERATED by scripts/build-user-guide.js — do not edit by hand.\n" +
  "window.USER_GUIDE = " +
  JSON.stringify(data, null, 2) +
  ";\n";
fs.writeFileSync(path.join(ROOT, "user-guide-data.js"), out, "utf8");

console.log(
  `Wrote user-guide-data.js: ${data.videos.english.length} English videos, ` +
    `${data.videos.hindi.length} Hindi videos.`,
);
